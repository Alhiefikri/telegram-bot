#!/usr/bin/env python3
"""Read-only, sanitized progress for a P04 local run; never prints spool contents."""
import argparse
import json
from pathlib import Path
import subprocess
import time

ROOT = Path(__file__).resolve().parents[2]


def progress(output):
    run = json.loads((output / 'run.json').read_text())
    record = {'event': 'baseline_progress', 'status': run['status'],
              'completed_cells': len(run.get('batches', [])),
              'recorded_attempts': sum(cell['attempts'] for cell in run.get('batches', [])),
              'completed_measured_cells': sum(not cell['cell']['warmup'] for cell in run.get('batches', []))}
    if 'offline_recovery' in run:
        record['retained_attempts_including_partial_cells'] = run['offline_recovery']['retained_records']
    if run['status'] != 'running':
        return record
    # The current run's UUID is already present in host evidence after its first cell.
    cells = run.get('batches', [])
    if not cells:
        record['phase'] = 'startup_or_seed'
        return record
    previous = cells[-1]['cell']['evidence_path']
    run_id = Path(previous).name.split('-', 1)[0]
    if len(run_id) != 32 or any(c not in '0123456789abcdef' for c in run_id):
        raise ValueError('invalid run identity')
    ids = subprocess.run(['docker', 'ps', '-q', '--filter', 'label=com.docker.compose.project=lhie-p01-laravel',
                          '--filter', 'label=com.docker.compose.service=app'], capture_output=True,
                         text=True, check=True, timeout=10).stdout.split()
    if len(ids) != 1:
        record['phase'] = 'runtime_unavailable'
        return record
    # Only names generated by runner.py are eligible; the full raw record never leaves PHP.
    script = r'''
$paths=glob('/var/www/html/storage/app/private/p04-evidence/'.$argv[1].'-*.jsonl');
if(!$paths){echo '{}';exit;}
usort($paths,static fn($a,$b)=>filemtime($b)<=>filemtime($a));
$path=$paths[0];$file=fopen($path,'r');$n=0;$states=['success'=>0,'error'=>0,'timeout'=>0,'unknown'=>0];$last=null;
while(($line=fgets($file))!==false){$row=json_decode($line,true);if(!is_array($row)||!isset($states[$row['outcome']??'']))continue;$n++;$states[$row['outcome']]++;$last=$row;}
fclose($file);$dimensions=[];
foreach(['dataset','profile','scenario','users','traffic','temperature','background','batch','warmup'] as $key){$dimensions[$key]=$last[$key]??null;}
echo json_encode(['active_cell'=>$dimensions,'cell_completed_attempts'=>$n,'cell_outcomes'=>$states,'seconds_since_spool_update'=>time()-filemtime($path)]);
'''
    observed = subprocess.run(['docker', 'exec', ids[0], 'php', '-r', script, run_id],
                              capture_output=True, text=True, check=True, timeout=15)
    record.update(json.loads(observed.stdout))
    return record


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    parser.add_argument('--follow', action='store_true')
    args = parser.parse_args()
    output = args.output.resolve()
    if not output.is_relative_to(ROOT / '.local'):
        parser.error('output must be below repository .local')
    while True:
        try:
            observed = progress(output)
        except (OSError, ValueError, KeyError, subprocess.SubprocessError):
            observed = {'event': 'baseline_progress', 'status': 'observation_unavailable'}
        print(json.dumps(observed, separators=(',', ':')), flush=True)
        if not args.follow or observed['status'] not in ('running', 'observation_unavailable'):
            return
        time.sleep(30)


if __name__ == '__main__':
    main()
