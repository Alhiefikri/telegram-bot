CREATE ROLE p02_migrator NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
CREATE ROLE p02_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
CREATE SCHEMA fixture AUTHORIZATION p02_migrator;
SET ROLE p02_migrator;
CREATE TABLE fixture.customers (
 id bigint PRIMARY KEY, email text NOT NULL UNIQUE, telegram_id bigint NOT NULL UNIQUE,
 password_hash text NOT NULL, created_at timestamp NOT NULL
);
CREATE TABLE fixture.credentials (
 id bigint PRIMARY KEY, format text NOT NULL CHECK (format IN ('legacy','structured')),
 secret text NOT NULL, identity_fingerprint text NOT NULL UNIQUE, state text NOT NULL
 CHECK (state IN ('available','reserved','allocated','retired')), created_at timestamp NOT NULL
);
CREATE TABLE fixture.orders (
 id bigint PRIMARY KEY, customer_id bigint NOT NULL REFERENCES fixture.customers(id),
 credential_id bigint REFERENCES fixture.credentials(id), amount bigint NOT NULL CHECK (amount > 0),
 currency text NOT NULL CHECK (currency IN ('IDR','USDT')), status text NOT NULL,
 provider_target text NOT NULL, created_at timestamp NOT NULL, deadline timestamp NOT NULL,
 CHECK (deadline >= created_at)
);
CREATE TABLE fixture.identities (
 id bigint PRIMARY KEY, credential_id bigint NOT NULL UNIQUE REFERENCES fixture.credentials(id),
 kind text NOT NULL CHECK (kind = 'email'), fingerprint text NOT NULL UNIQUE
);
CREATE TABLE fixture.ledger (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id bigint NOT NULL REFERENCES fixture.customers(id),
 order_id bigint REFERENCES fixture.orders(id), currency text NOT NULL CHECK (currency IN ('IDR','USDT')),
 amount bigint NOT NULL CHECK (amount > 0), direction smallint NOT NULL CHECK (direction IN (-1,1)),
 balance_after bigint NOT NULL CHECK (balance_after >= 0), source text NOT NULL UNIQUE,
 created_at timestamp NOT NULL
);
CREATE TABLE fixture.accounts (
 customer_id bigint NOT NULL REFERENCES fixture.customers(id), currency text NOT NULL,
 balance bigint NOT NULL CHECK (balance >= 0), PRIMARY KEY(customer_id,currency)
);
CREATE TABLE fixture.effects (
 id bigint PRIMARY KEY, order_id bigint NOT NULL REFERENCES fixture.orders(id), state text NOT NULL,
 chat_id bigint NOT NULL, stable_key text NOT NULL UNIQUE, created_at timestamp NOT NULL
);
CREATE FUNCTION fixture.immutable_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'immutable history'; END $$;
CREATE TRIGGER ledger_immutable BEFORE UPDATE OR DELETE ON fixture.ledger
 FOR EACH ROW EXECUTE FUNCTION fixture.immutable_history();
CREATE TRIGGER identity_immutable BEFORE UPDATE OR DELETE ON fixture.identities
 FOR EACH ROW EXECUTE FUNCTION fixture.immutable_history();
REVOKE ALL ON SCHEMA fixture FROM PUBLIC;
GRANT USAGE ON SCHEMA fixture TO p02_runtime;
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA fixture TO p02_runtime;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA fixture TO p02_runtime;
RESET ROLE;
